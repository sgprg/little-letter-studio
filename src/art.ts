export function svgArt(id:string, colored=false):string {
  const a=artwork[id];
  const colors=['#ffd77c','#90cfb6','#9ebbec','#edafc2','#d2bfed','#ffbd91'];
  return `<svg viewBox="100 70 600 510" xmlns="http://www.w3.org/2000/svg" aria-hidden="true"><g stroke="#38425c" stroke-width="5.5" stroke-linecap="round" stroke-linejoin="round">${a.regions.map((r,i)=>`<path d="${r.d}" fill="${colored?colors[i%colors.length]:'#fff'}"/>`).join('')}${a.lines.map(d=>`<path d="${d}" fill="none"/>`).join('')}</g>${a.dots.map(([x,y,r])=>`<circle cx="${x}" cy="${y}" r="${r}" fill="#38425c"/>`).join('')}</svg>`;
}
